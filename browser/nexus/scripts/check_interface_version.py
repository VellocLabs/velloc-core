"""Bridge interface version: sync + ninja-time gate against nexus_web.

SINGLE SOURCE OF TRUTH: the `NEXUS_INTERFACE_VERSION=<int>` key in
custom_browser/VERSION. It fans out as generated artifacts:
  - C++: nexus_interface_version.inc (gen_product_version.py, at build
    time — always in sync by construction), wrapped by
    browser/nexus/nexus_interface_version.h
  - JS:  nexus_web/src/browser/bridge/protocol/interfaceVersion.gen.ts —
    GENERATED BY THIS SCRIPT (`--sync`) and COMMITTED in the nexus_web
    repo (its Cloudflare CI builds from that repo alone, so the artifact
    must exist there)

Modes:
  default (check): fail if the sibling nexus_web checkout's committed
    interfaceVersion.gen.ts disagrees with VERSION. Wired as a GN action
    in browser/nexus/BUILD.gn (`:check_interface_version`), so any binary
    build fails on drift — this closes the dev-flow gap URL pinning
    leaves open (localhost serves an unversioned path). The TS file is
    reported via a depfile so ninja re-runs the check when either side
    changes. Builds without a nexus_web checkout (isolated CI) can set
    the GN arg `skip_nexus_interface_version_check = true`.
  --sync: regenerate interfaceVersion.gen.ts from VERSION. Run after
    bumping NEXUS_INTERFACE_VERSION, then commit both repos (web side
    first).

See docs/agents/nexus-interface-versioning.md.
"""

import argparse
import os
import re
import sys

VERSION_KEY_PATTERN = re.compile(
    r"^NEXUS_INTERFACE_VERSION=(\d+)\s*$", re.MULTILINE)
TS_PATTERN = re.compile(
    r"^export const NEXUS_INTERFACE_VERSION = (\d+)$", re.MULTILINE)

# Path of the generated guest-side constant inside a nexus_web checkout.
TS_RELATIVE_PATH = os.path.join(
    "src", "browser", "bridge", "protocol", "interfaceVersion.gen.ts")

TS_TEMPLATE = """\
// Generated file. Do not edit.
// Source of truth: src/custom_browser/VERSION (NEXUS_INTERFACE_VERSION).
// Regenerate with:
//   python src/custom_browser/browser/nexus/scripts/check_interface_version.py --sync
// The custom_browser ninja gate (same script, check mode) fails any binary
// build whose sibling nexus_web checkout has a stale copy of this file.
export const NEXUS_INTERFACE_VERSION = {version}
"""


def _default_version_file():
  """<root>/src/custom_browser/VERSION, derived from this script's location
  (<root>/src/custom_browser/browser/nexus/scripts/<this file>)."""
  here = os.path.dirname(os.path.abspath(__file__))
  return os.path.abspath(os.path.join(here, *[os.pardir] * 3, "VERSION"))


def _default_nexus_web_dir():
  """Derives the sibling nexus_web checkout from this script's location.

  Monorepo layout: <root>/src/custom_browser/browser/nexus/scripts/<this file>
  and <root>/nexus_web.
  """
  here = os.path.dirname(os.path.abspath(__file__))
  root = os.path.abspath(os.path.join(here, *[os.pardir] * 5))
  return os.path.join(root, "nexus_web")


def _parse(path, pattern, side):
  try:
    with open(path, encoding="utf-8") as f:
      content = f.read()
  except OSError as e:
    return None, f"could not read the {side} file {path}: {e}"
  match = pattern.search(content)
  if not match:
    return None, (
        f"could not find the NEXUS_INTERFACE_VERSION declaration in {path}; "
        f"the declaration must stay on one line with a literal integer")
  return int(match.group(1)), None


def _write_outputs(args, extra_dep=None):
  deps = [args.version_file]
  if extra_dep:
    deps.append(extra_dep)
  # Depfile paths are resolved by ninja relative to the build dir (this
  # script's cwd); keep them in the same form the action received them, and
  # normalize to forward slashes for the depfile grammar.
  with open(args.depfile, "w", encoding="utf-8") as f:
    f.write("{}: {}\n".format(
        args.stamp.replace("\\", "/"),
        " ".join(d.replace("\\", "/") for d in deps)))
  with open(args.stamp, "w", encoding="utf-8") as f:
    f.write("")


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--version-file", default="",
                      help="custom_browser/VERSION (default: derived)")
  parser.add_argument("--stamp", help="Stamp file to write (check mode)")
  parser.add_argument("--depfile", help="Depfile to write (check mode)")
  parser.add_argument("--nexus-web-dir", default="",
                      help="nexus_web checkout dir (default: derived sibling)")
  parser.add_argument("--sync", action="store_true",
                      help="Regenerate the nexus_web TS constant from "
                           "VERSION instead of checking")
  parser.add_argument("--skip", action="store_true",
                      help="Record a warning and pass without checking")
  args = parser.parse_args()

  version_file = args.version_file or _default_version_file()
  args.version_file = version_file
  nexus_web_dir = args.nexus_web_dir or _default_nexus_web_dir()
  ts_path = os.path.join(nexus_web_dir, TS_RELATIVE_PATH)

  source_version, err = _parse(version_file, VERSION_KEY_PATTERN,
                               "custom_browser/VERSION")
  if err and not args.skip:
    print(f"nexus interface version: {err}", file=sys.stderr)
    return 1

  if args.sync:
    os.makedirs(os.path.dirname(ts_path), exist_ok=True)
    with open(ts_path, "w", encoding="utf-8", newline="\n") as f:
      f.write(TS_TEMPLATE.format(version=source_version))
    print(f"nexus interface version: wrote v{source_version} to {ts_path}. "
          f"Commit it in the nexus_web repo (web side first).")
    return 0

  if not args.stamp or not args.depfile:
    parser.error("--stamp and --depfile are required in check mode")

  if args.skip:
    print("WARNING: nexus interface version check SKIPPED "
          "(skip_nexus_interface_version_check=true); this binary's bridge "
          "contract has not been verified against nexus_web.",
          file=sys.stderr)
    _write_outputs(args)
    return 0

  if not os.path.isfile(ts_path):
    print(f"nexus interface version check FAILED: no nexus_web checkout at "
          f"{nexus_web_dir} (expected {ts_path}).\n"
          f"Either restore the sibling checkout (and run this script with "
          f"--sync if the generated file is missing), point the GN arg "
          f"`nexus_web_dir` at one, or set "
          f"`skip_nexus_interface_version_check = true` to build without "
          f"the guest-runtime pairing guarantee.", file=sys.stderr)
    return 1

  ts_version, err = _parse(ts_path, TS_PATTERN, "nexus_web")
  if err:
    print(f"nexus interface version check FAILED: {err}", file=sys.stderr)
    return 1

  if source_version != ts_version:
    print(f"nexus interface version check FAILED: the bridge interface "
          f"versions have diverged.\n"
          f"  VERSION   v{source_version}  ({version_file})\n"
          f"  nexus_web v{ts_version}  ({ts_path})\n"
          f"The nexus_web copy is a generated artifact — regenerate it with\n"
          f"  python {os.path.abspath(__file__)} --sync\n"
          f"and commit it (web side first). "
          f"See docs/agents/nexus-interface-versioning.md.",
          file=sys.stderr)
    return 1

  _write_outputs(args, extra_dep=ts_path)
  return 0


if __name__ == "__main__":
  sys.exit(main())
